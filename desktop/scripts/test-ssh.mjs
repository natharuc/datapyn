import assert from "node:assert/strict";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { chromium } from "playwright";

// Isolated headless form/trust fixture. No actual SSH, database, OS keyring or desktop is contacted.
const root = resolve(dirname(fileURLToPath(import.meta.url)), ".."), route = "/__ssh_test";
const server = await createServer({ root, cacheDir: "node_modules/.vite-ssh-tests", plugins: [{ name: "ssh-fixture", configureServer(server) { server.middlewares.use(route, async (_request, response) => {
  response.setHeader("Content-Type", "text/html");
  response.end(await server.transformIndexHtml(route, '<!doctype html><html><body><div id="root"></div><script type="module" src="/tests/ssh.fixture.tsx"></script></body></html>'));
}); } }], server: { host: "127.0.0.1", port: 0, watch: null } });
let browser;
await server.listen();
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 960, height: 800 }, reducedMotion: "reduce" }), errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const address = `http://127.0.0.1:${server.httpServer.address().port}${route}`;
  for (const theme of ["light", "dark"]) {
    await page.goto(address); await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    const dialog = page.locator(".connection-dialog");
    await dialog.getByLabel("Tipo do banco").selectOption("postgresql");
    assert.equal(await dialog.getByLabel("Usar túnel SSH").isChecked(), false);
    assert.equal(await dialog.getByLabel("Servidor SSH", { exact: true }).count(), 0);
    await dialog.getByLabel("Nome", { exact: true }).fill("DocFis STG");
    await dialog.getByLabel("Servidor", { exact: true }).fill("pg.internal");
    await dialog.getByLabel("Banco", { exact: true }).fill("docfis_stg");
    await dialog.getByLabel("Usar túnel SSH").check();
    assert.equal(await dialog.getByLabel("Porta SSH", { exact: true }).inputValue(), "22");
    await dialog.getByLabel("Servidor SSH", { exact: true }).fill("vps.example");
    await dialog.getByLabel("Usuário SSH", { exact: true }).fill("deploy");
    await dialog.getByLabel("Senha SSH", { exact: true }).fill("ssh-secret");
    await dialog.getByText("TLS PostgreSQL", { exact: true }).click();
    await dialog.getByLabel("Modo TLS").selectOption("verify-full");
    await dialog.getByLabel("Certificado CA (opcional)").fill("/certs/ca.pem");
    await dialog.getByRole("button", { name: "Testar conexão", exact: true }).click();
    const trust = page.getByRole("dialog", { name: "Confirmar servidor SSH" });
    await trust.waitFor();
    assert((await trust.textContent()).includes("vps.example:22")); assert((await trust.textContent()).includes("SHA256:"));
    assert.equal(await page.evaluate(() => window.__SSH_TEST__.calls.filter(call => call.method === "ssh.host_key.trust").length), 0);
    await trust.getByRole("button", { name: "Cancelar", exact: true }).click();
    await dialog.getByRole("alert").filter({ hasText: "cancelada" }).waitFor();
    assert.equal(await page.evaluate(() => window.__SSH_TEST__.calls.filter(call => call.method === "connection.test").length), 1);
    await dialog.getByRole("button", { name: "Testar conexão", exact: true }).click(); await trust.waitFor();
    await trust.getByRole("button", { name: "Confiar e continuar", exact: true }).click();
    await dialog.getByRole("status").filter({ hasText: "SSH e banco" }).waitFor();
    const tested = await page.evaluate(() => window.__SSH_TEST__.calls.filter(call => call.method === "connection.test").at(-1).params.config);
    assert.equal(tested.host, "pg.internal"); assert.equal(tested.ssh.host, "vps.example"); assert.equal(tested.sslmode, "verify-full"); assert.equal(tested.sslrootcert, "/certs/ca.pem");
    await dialog.getByLabel("Autenticação SSH").selectOption("private_key");
    assert.equal(await dialog.getByLabel("Senha SSH", { exact: true }).count(), 0);
    await dialog.getByRole("button", { name: "Escolher chave privada SSH", exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll(".connection-dialog input")].some(input => input.value === "/keys/id_ed25519"));
    assert.equal(await dialog.getByLabel("Chave privada SSH", { exact: true }).inputValue(), "/keys/id_ed25519");
    await dialog.getByLabel("Passphrase (opcional)").fill("key-secret");
    await dialog.getByText("Colar connection string", { exact: true }).click();
    await dialog.getByLabel("URI ou string .NET/ODBC").fill("postgresql://reader:pwd@pg.internal:5433/docfis_prd?sslmode=verify-full&sslrootcert=%2Fcerts%2Fca.pem");
    await dialog.getByRole("button", { name: "Preencher campos", exact: true }).click();
    assert.equal(await dialog.getByLabel("Usar túnel SSH").isChecked(), true);
    assert.equal(await dialog.getByLabel("Servidor SSH", { exact: true }).inputValue(), "vps.example");
    assert.equal(await dialog.getByLabel("Passphrase (opcional)").inputValue(), "key-secret");
    const bounds = await dialog.evaluate(element => ({ overflow: element.scrollWidth > element.clientWidth + 1, width: element.getBoundingClientRect().width }));
    assert.equal(bounds.overflow, false); assert(bounds.width < 960);
    await dialog.getByRole("button", { name: "Salvar", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    const saved = await page.evaluate(() => window.__SSH_TEST__.calls.find(call => call.method === "connections.save").params);
    assert.equal(saved.ssh_passphrase, "key-secret"); assert.equal(saved.save_ssh_credentials, true); assert.equal(saved.ssh_password, undefined);
    assert.equal(saved.connection.config.ssh.passphrase, undefined); assert.equal(saved.connection.config.ssh.password, undefined);
    assert.equal(saved.connection.config.host, "pg.internal"); assert.equal(saved.connection.config.port, 5433);
    assert.equal(saved.connection.config.ssh.port, 22);
    await page.evaluate(() => window.__SSH_OPEN_EDIT__()); await dialog.waitFor();
    assert.equal(await dialog.getByLabel("Passphrase (opcional)").getAttribute("placeholder"), "Deixe em branco para manter a passphrase salva");
    await dialog.getByText("Colar connection string", { exact: true }).click();
    await dialog.getByLabel("URI ou string .NET/ODBC").fill("postgresql://reader:imported-password@pg.internal:5432/new_bank?sslmode=verify-full");
    await dialog.getByRole("button", { name: "Preencher campos", exact: true }).click();
    assert.equal(await dialog.getByLabel("Passphrase (opcional)").inputValue(), "");
    assert.equal(await dialog.getByLabel("Passphrase (opcional)").getAttribute("placeholder"), "Deixe em branco para manter a passphrase salva");
    await page.evaluate(() => window.__SSH_TEST__.resetTrust());
    await dialog.getByRole("button", { name: "Testar conexão", exact: true }).click(); await trust.waitFor();
    const editedTest = await page.evaluate(() => window.__SSH_TEST__.calls.filter(call => call.method === "connection.test").at(-1).params);
    assert.equal(editedTest.connection_id, "saved"); assert.equal(editedTest.resolve_database_password, false);
    assert.equal(editedTest.config.ssh.host, "vps.example"); assert.equal(editedTest.config.password, "imported-password");
    await page.evaluate(() => window.__SSH_CLOSE__()); await trust.waitFor({ state: "detached" });
    assert.equal(await page.evaluate(() => window.__SSH_TEST__.challenge), undefined);
    await page.evaluate(() => { window.__SSH_TEST__.trusted.add("vps.example"); window.__SSH_TEST__.holdTests(); window.__SSH_OPEN_EDIT__(); });
    await dialog.waitFor(); await dialog.getByRole("button", { name: "Testar conexão", exact: true }).click();
    await page.waitForFunction(() => window.__SSH_TEST__.pendingTestCount === 1);
    const pendingTestId = await page.evaluate(() => window.__SSH_TEST__.calls.filter(call => call.method === "connection.test").at(-1).params.test_id);
    await dialog.getByRole("button", { name: "Fechar", exact: true }).click(); await dialog.waitFor({ state: "detached" });
    await page.waitForFunction(() => window.__SSH_TEST__.pendingTestCount === 0);
    assert.equal(await page.evaluate(() => window.__SSH_TEST__.calls.filter(call => call.method === "connection.test_cancel").at(-1).params.test_id), pendingTestId);
    assert.equal(await page.evaluate(() => window.__SSH_TEST__.challenge), undefined);
    console.log(`PASS ${theme}: SSH form, password/key, fingerprint approval/cancel, bank/TLS independence, secure save, edit and unmount cancellation`);
  }
  assert.deepEqual(errors, []);
} finally { await browser?.close(); await server.close(); }
